//   二版躲成电报 ——「箱不打开。照册点，点完钉盖。」省字省出了谜语；
//   三版是完整句子，但仍有几处主语在飘（「不要问东西从哪来」—— 谁不要问？）。
//
// 这一版的规矩，四条：
//   1. **一句话说一件事。** 不合并，不用分号一段接三段。
//   2. **主语必须出现。** 谁做什么，写出来：「我们照着册子数了一遍」「莫斯塔拉那边不要问」。
//      主语指的是人、是货、是那张册子，都得让读者一眼找得到。
//   3. **谓语用动作。** 「点一遍」「关回去」「赶走他」—— 不用「予以清点」这类蒙人的词。
//   4. **语气分两种，不许混。**
//        命令 —— 对押运的人下指令：不准、不要、立刻；
//        陈述 —— 对团部回话：已经、少了、空着。
//      一份文书里只有一种语气；混着写就会读成半命令半汇报。
//
// 口径照 docs/剧情_小刻与骑士团.md：
//   §5.1  食人魔"曾经是人"的证据只能走现场与文件两类载体 —— 名册是文件那一类；
//   §5.2  工艺是本地锻铁、皮革、粗布、石槽陶罐，没有未来科技；能修、能复制、有工序；
//   §5.3  动机是打通"山地 → 河谷 → 海口"，地名用哥维纳 / 科尼察 / 莫斯塔拉；
//   §5.4  团长本人不出场，只以**署名**存在，姓名未定 —— 落款只能写"团长"。
//
// 三条不能破：不写团长姓名；不点人头（不给数字）；不解释改造工艺的原理。
//
// 三份东西各在一处，读的顺序就是链路顺序：
//   转运令   —— 命令。这批货是流水线的末端；
//   随箱名册 —— 账。把「人 → 兽」写成一道工序；
//   点收回执 —— 回文。从收方那一头看，这是要持续供货的买卖。

